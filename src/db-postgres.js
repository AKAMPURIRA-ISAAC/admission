export async function listApplications({ search, status, limit, offset }) {
  const filters = [];
  const parameters = [];

  if (search) {
    filters.push("(LOWER(student_name) LIKE LOWER(?) OR LOWER(admission_number) LIKE LOWER(?))");
    parameters.push(`%${search}%`, `%${search}%`);
  }
  if (status) {
    filters.push("status = ?");
    parameters.push(status);
  }

  const where = filters.length ? `WHERE ${filters.join(" AND ")}` : "";
  const total = await query(`SELECT COUNT(*) AS count FROM applications ${where}`, parameters);
  const applications = await query(`
    SELECT ${applicationSummaryColumns}
    FROM applications
    ${where}
    ORDER BY created_at DESC
    LIMIT ? OFFSET ?
  `, [...parameters, limit, offset]);

  return { applications: applications.rows, total: Number(total.rows[0].count) };
}

